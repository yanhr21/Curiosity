#!/usr/bin/env bash
set -euo pipefail

# Launch trained residual-adapter evaluation through the official Newton
# Panda hydro camera/export path. This script submits no new allocation.

ROOT="${ROOT:-/public/home/yanhongru/Curiosity}"
RUN_TAG="${RUN_TAG:-residual_adapter_eval_v1_empty_medium_validation_$(date +%Y%m%d_%H%M%S)}"
WINDOW_NAME="${WINDOW_NAME:-residual_adapter_eval}"
SCENE="${SCENE:-cube}"
TRACKED_OBJECT="${TRACKED_OBJECT:-existing_cup_asset}"
CONTROLLER_MODE="${CONTROLLER_MODE:-lift_hold_learned_residual}"
FINAL_HOLD_DURATION="${FINAL_HOLD_DURATION:-2.5}"
PHYSICS_VARIANT_LABEL="${PHYSICS_VARIANT_LABEL:-learned_residual_empty_medium_validation}"
OBJECT_MASS_KG="${OBJECT_MASS_KG:-0.08}"
OBJECT_FRICTION_MU="${OBJECT_FRICTION_MU:-0.8}"
FEEDBACK_MIN_CONTACT_COUNT="${FEEDBACK_MIN_CONTACT_COUNT:-58}"
FEEDBACK_ACCEL_THRESHOLD="${FEEDBACK_ACCEL_THRESHOLD:-6.5}"
FEEDBACK_HEIGHT_DROP_THRESHOLD="${FEEDBACK_HEIGHT_DROP_THRESHOLD:-0.015}"
FEEDBACK_INITIAL_LIFT_DURATION_SCALE="${FEEDBACK_INITIAL_LIFT_DURATION_SCALE:-1.65}"
FEEDBACK_LIFT_DURATION_SCALE_MAX="${FEEDBACK_LIFT_DURATION_SCALE_MAX:-1.05}"
FEEDBACK_HOLD_HEIGHT_STEP="${FEEDBACK_HOLD_HEIGHT_STEP:-0.0005}"
FEEDBACK_HOLD_HEIGHT_OFFSET_MAX="${FEEDBACK_HOLD_HEIGHT_OFFSET_MAX:-0.005}"
FEEDBACK_STABILIZATION_STEP="${FEEDBACK_STABILIZATION_STEP:-0.05}"
FEEDBACK_STABILIZATION_MAX="${FEEDBACK_STABILIZATION_MAX:-0.3}"
PRE_RECORD_WARMUP_STEPS="${PRE_RECORD_WARMUP_STEPS:-15}"
RESIDUAL_ADAPTER_CHECKPOINT="${RESIDUAL_ADAPTER_CHECKPOINT:-$ROOT/checkpoints/residual_adapter_trainer_v1_20260627/residual_adapter_trainer_v1_train_20260627_0548.pt}"
RESIDUAL_ADAPTER_ACTIVE_THRESHOLD="${RESIDUAL_ADAPTER_ACTIVE_THRESHOLD:-0.5}"
NUM_STEPS="${NUM_STEPS:-360}"
SAMPLE_STEPS="${SAMPLE_STEPS:-0,45,90,135,180,225,270,315,359}"

cd "$ROOT"

case "$CONTROLLER_MODE" in
  lift_hold_learned_residual)
    ;;
  *)
    echo "ERROR: residual adapter evaluation requires CONTROLLER_MODE=lift_hold_learned_residual." >&2
    exit 2
    ;;
esac

if [[ ! -f "$RESIDUAL_ADAPTER_CHECKPOINT" ]]; then
  echo "ERROR: missing residual adapter checkpoint: $RESIDUAL_ADAPTER_CHECKPOINT" >&2
  exit 3
fi

bash -n "$ROOT/experiments/configs/launch_newton_panda_hydro_camera_export_tmux.sh"
bash -n "$ROOT/experiments/configs/run_newton_panda_hydro_camera_export_v2_in_alloc.sh"

RUN_TAG="$RUN_TAG" \
WINDOW_NAME="$WINDOW_NAME" \
SCENE="$SCENE" \
TRACKED_OBJECT="$TRACKED_OBJECT" \
CONTROLLER_MODE="$CONTROLLER_MODE" \
FINAL_HOLD_DURATION="$FINAL_HOLD_DURATION" \
PHYSICS_VARIANT_LABEL="$PHYSICS_VARIANT_LABEL" \
OBJECT_MASS_KG="$OBJECT_MASS_KG" \
OBJECT_FRICTION_MU="$OBJECT_FRICTION_MU" \
FEEDBACK_MIN_CONTACT_COUNT="$FEEDBACK_MIN_CONTACT_COUNT" \
FEEDBACK_ACCEL_THRESHOLD="$FEEDBACK_ACCEL_THRESHOLD" \
FEEDBACK_HEIGHT_DROP_THRESHOLD="$FEEDBACK_HEIGHT_DROP_THRESHOLD" \
FEEDBACK_INITIAL_LIFT_DURATION_SCALE="$FEEDBACK_INITIAL_LIFT_DURATION_SCALE" \
FEEDBACK_LIFT_DURATION_SCALE_MAX="$FEEDBACK_LIFT_DURATION_SCALE_MAX" \
FEEDBACK_HOLD_HEIGHT_STEP="$FEEDBACK_HOLD_HEIGHT_STEP" \
FEEDBACK_HOLD_HEIGHT_OFFSET_MAX="$FEEDBACK_HOLD_HEIGHT_OFFSET_MAX" \
FEEDBACK_STABILIZATION_STEP="$FEEDBACK_STABILIZATION_STEP" \
FEEDBACK_STABILIZATION_MAX="$FEEDBACK_STABILIZATION_MAX" \
PRE_RECORD_WARMUP_STEPS="$PRE_RECORD_WARMUP_STEPS" \
RESIDUAL_ADAPTER_CHECKPOINT="$RESIDUAL_ADAPTER_CHECKPOINT" \
RESIDUAL_ADAPTER_ACTIVE_THRESHOLD="$RESIDUAL_ADAPTER_ACTIVE_THRESHOLD" \
NUM_STEPS="$NUM_STEPS" \
SAMPLE_STEPS="$SAMPLE_STEPS" \
bash "$ROOT/experiments/configs/launch_newton_panda_hydro_camera_export_tmux.sh"
