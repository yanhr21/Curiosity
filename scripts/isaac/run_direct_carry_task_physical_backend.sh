  front_mid)
    DEFAULT_PAYLOAD_LOCAL_X="0.20"
    DEFAULT_PAYLOAD_LOCAL_Z="0.04"
    DEFAULT_TORSO_Z="0.55"
    ;;
  low_front)
    DEFAULT_PAYLOAD_LOCAL_X="0.24"
    DEFAULT_PAYLOAD_LOCAL_Z="-0.02"
    DEFAULT_TORSO_Z="0.58"
    ;;
  chest_high)
    DEFAULT_PAYLOAD_LOCAL_X="0.16"
    DEFAULT_PAYLOAD_LOCAL_Z="0.12"
    DEFAULT_TORSO_Z="0.55"
    ;;
  front_reach)
    DEFAULT_PAYLOAD_LOCAL_X="0.28"
    DEFAULT_PAYLOAD_LOCAL_Z="0.04"
    DEFAULT_TORSO_Z="0.56"
    ;;
  close_mid)
    DEFAULT_PAYLOAD_LOCAL_X="0.12"
    DEFAULT_PAYLOAD_LOCAL_Z="0.05"
    DEFAULT_TORSO_Z="0.55"
    ;;
  *)
    echo "Unknown CARRY_POSTURE=${CARRY_POSTURE}; expected front_mid, low_front, chest_high, front_reach, or close_mid" >&2
    exit 5
    ;;
esac

