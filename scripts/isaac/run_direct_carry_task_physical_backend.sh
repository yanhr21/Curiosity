  "STOP_THRESHOLD=${STOP_THRESHOLD:-0.002}"
  "STATIC_FRICTION=${STATIC_FRICTION:-3.0}"
  "DYNAMIC_FRICTION=${DYNAMIC_FRICTION:-2.5}"
  "ENABLE_SUPPORT_FOOT_CONTACT_REPORT=${ENABLE_SUPPORT_FOOT_CONTACT_REPORT:-0}"
  "SUPPORT_FOOT_CONTACT_REPORT_THRESHOLD=${SUPPORT_FOOT_CONTACT_REPORT_THRESHOLD:-0.0}"
  "SUPPORT_FOOT_EFFORT_CONTACT_THRESHOLD=${SUPPORT_FOOT_EFFORT_CONTACT_THRESHOLD:-1.0}"
  "SUPPORT_FOOT_CONTINUITY_GRACE_STEPS=${SUPPORT_FOOT_CONTINUITY_GRACE_STEPS:-0}"
