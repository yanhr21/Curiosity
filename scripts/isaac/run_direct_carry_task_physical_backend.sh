#!/usr/bin/env bash
set -euo pipefail

if [[ "$(hostname)" == mgmtserver* ]]; then
  echo "Refusing to run Isaac simulation on login/management node: $(hostname)" >&2
  exit 2
fi

ROOT_DIR="${ROOT_DIR:-/public/home/yanhongru/Curiosity}"
STAMP="${STAMP:-$(date +%Y%m%d_%H%M%S)}"
OUTPUT_DIR="${OUTPUT_DIR:-${ROOT_DIR}/experiments/outputs/direct_carry_task_physical_backend/${STAMP}}"
BACKEND_OUTPUT_DIR="${BACKEND_OUTPUT_DIR:-${OUTPUT_DIR}/backend_anchored_cradle}"
BACKEND_STAMP="${BACKEND_STAMP:-${STAMP}_backend_anchored_cradle}"
BACKEND_LOG="${ROOT_DIR}/logs/core_world_anchored_footstep_carrier/core_world_anchored_footstep_carrier_${BACKEND_STAMP}.log"
SUPPORT_MODE="${SUPPORT_MODE:-replant_world_joint}"
CARRY_POSTURE="${CARRY_POSTURE:-front_mid}"

mkdir -p "${OUTPUT_DIR}" "${BACKEND_OUTPUT_DIR}"
cd "${ROOT_DIR}"

case "${SUPPORT_MODE}" in
  replant_world_joint)
    SUPPORT_ARGS=(--no-fix-anchor-to-world --replant-anchor-world-joint --cumulative-cycle-target)
    DEFAULT_STEP_LENGTH="0.08"
    DEFAULT_CONTROLLER_MODE="physical_anchored_cradle"
    ;;
  fixed_anchor)
    SUPPORT_ARGS=(--fix-anchor-to-world)
    DEFAULT_STEP_LENGTH="${TARGET_X:-0.32}"
    DEFAULT_CONTROLLER_MODE="physical_fixed_anchor_cradle"
    ;;
  dynamic_anchor_feet)
    SUPPORT_ARGS=(--no-fix-anchor-to-world --support-foot-mode fixed_to_anchor --disable-support-reposition)
    DEFAULT_STEP_LENGTH="${TARGET_X:-0.32}"
    DEFAULT_CONTROLLER_MODE="physical_dynamic_anchor_feet_cradle"
    ;;
  legged_anchor_feet)
    SUPPORT_ARGS=(--no-fix-anchor-to-world --support-foot-mode x_prismatic_to_anchor --disable-support-reposition --use-support-foot-drive)
    DEFAULT_STEP_LENGTH="${TARGET_X:-0.16}"
    DEFAULT_CONTROLLER_MODE="physical_legged_anchor_feet_cradle"
    ;;
  alternating_anchor_feet)
    SUPPORT_ARGS=(--no-fix-anchor-to-world --support-foot-mode xz_prismatic_to_anchor --disable-support-reposition --use-support-foot-drive)
    DEFAULT_STEP_LENGTH="${STEP_LENGTH:-0.08}"
    DEFAULT_CONTROLLER_MODE="physical_alternating_anchor_feet_cradle"
    ;;
  alternating_placement_feet)
    SUPPORT_ARGS=(
      --no-fix-anchor-to-world
      --support-foot-mode xz_prismatic_to_anchor
      --support-foot-placement-mode alternating_directional_x
      --disable-support-reposition
      --use-support-foot-drive
    )
    DEFAULT_STEP_LENGTH="${STEP_LENGTH:-0.08}"
    DEFAULT_CONTROLLER_MODE="physical_alternating_placement_feet_cradle"
    ;;
  *)
    echo "Unknown SUPPORT_MODE=${SUPPORT_MODE}; expected replant_world_joint, fixed_anchor, dynamic_anchor_feet, legged_anchor_feet, alternating_anchor_feet, or alternating_placement_feet" >&2
    exit 4
    ;;
esac

